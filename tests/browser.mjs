import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const errors = [];
const page = await browser.newPage({ viewport: { width: 1440, height: 1040 }, deviceScaleFactor: 1 });
page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto((process.env.TEST_URL || 'http://127.0.0.1:5173') + '/lab.html');
  await page.locator('#pitch').waitFor();
  await page.waitForTimeout(1500);
  assert.ok(await page.evaluate(() => Boolean(document.querySelector('#pitch').getContext('webgl2'))), 'WebGL2 context created');
  await page.screenshot({ path: 'test-results/desktop.png' });
  await page.locator('#power').fill('90');
  await page.locator('#shoot').click();
  await page.waitForFunction(() => document.querySelector('#goals').textContent.includes('/ 1'), { timeout: 10000 });
  assert.match(await page.locator('#goals').textContent(), /^1/);
  assert.equal(await page.locator('#balance').textContent(), '275');
  await page.screenshot({ path: 'test-results/goal.png' });
  await page.waitForFunction(() => !document.querySelector('#shoot').disabled);
  await page.locator('#pause').click();
  assert.equal(await page.locator('#shoot').isDisabled(), true);
  await page.locator('#resume').click();
  assert.equal(await page.locator('#shoot').isEnabled(), true);
  await page.locator('#shop-nav').click();
  await page.locator('[data-buy="sunset"]').click();
  assert.equal(await page.locator('#shop-balance').textContent(), '155');
  assert.equal(await page.locator('[data-buy="sunset"]').isDisabled(), true);
  await page.locator('[data-buy="samurai"]').click();
  assert.equal(await page.locator('#shop-message').textContent(), 'Niet genoeg munten');
  await page.screenshot({ path: 'test-results/shop.png' });
  await page.locator('#shop .close').click();
  await page.reload();
  await page.locator('#shop-nav').click();
  assert.equal(await page.locator('#shop-balance').textContent(), '155');
  assert.equal(await page.locator('[data-buy="sunset"]').isDisabled(), true);
  await page.locator('#shop .close').click();
  await page.locator('[data-mode="match"]').click();
  await page.waitForFunction(() => parseInt(document.querySelector('#secondary-value').textContent) < 60, null, { timeout: 30000 });
  assert.match(await page.locator('#secondary-value').textContent(), /5[0-9]s/);
  await page.locator('#pause').click();
  const pausedTime = await page.locator('#secondary-value').textContent();
  await page.waitForTimeout(1100);
  assert.equal(await page.locator('#secondary-value').textContent(), pausedTime);
  await page.locator('#resume').click();
  await page.locator('[data-mode="arcade"]').click();
  assert.match(await page.locator('#round-caption').textContent(), /5 LEVENS/);
  await page.locator('#help-button').click();
  await page.keyboard.press('Escape');
  await page.locator('#restart').click();
  assert.equal(await page.locator('#shoot').isEnabled(), true);
  await page.locator('#fps').selectOption('30');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(600);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'no mobile horizontal overflow');
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true });
  await page.locator('#shoot').scrollIntoViewIfNeeded();
  await page.locator('#shoot').click();
  await page.waitForFunction(() => document.querySelector('#goals').textContent.includes('/ 1'));
  assert.deepEqual(errors, []);
  console.log('PASS: WebGL, desktop goal/reward, pause, shop purchase/insufficient funds/persistence, match timer pause, arcade reset, help, 30fps setting, mobile layout and shooting; no page errors.');
} finally { await browser.close(); }
